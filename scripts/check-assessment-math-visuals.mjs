import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

const types = read('src/types/assessmentVisual.ts')
const tikz = read('src/lib/assessmentTikz.ts')
const renderer = read('src/components/AssessmentTikzDiagram.tsx')
const diagram = read('src/components/AssessmentDiagram.tsx')
const clientGeneration = read('src/lib/assessmentGeneration.ts')
const edgeContract = read('supabase/functions/_shared/assessment-contract.ts')
const generator = read('supabase/functions/assessment-question-generator/index.ts')

for (const primitive of ['cartesianAxes', 'cartesianPlot']) assert.match(types, new RegExp(`type: '${primitive}'`), `${primitive} must remain part of the safe visual DSL`)
assert.match(types, /points:\s*Array<\{ x: number; y: number \}>/, 'Cartesian plots use bounded sampled numeric points')
assert.doesNotMatch(types, /cartesianPlot[\s\S]{0,500}(?:formula|expression|script|code):\s*string/i, 'Cartesian plots must never evaluate model-supplied formulas or code')

assert.match(tikz, /\\\\begin\{tikzpicture\}/, 'validated visuals are deterministically translated to real TikZ')
assert.match(tikz, /escapeTikzText/, 'TikZ labels are escaped before compilation')
assert.match(tikz, /case 'cartesianAxes'/, 'TikZ translator renders Cartesian axes')
assert.match(tikz, /case 'cartesianPlot'/, 'TikZ translator renders Cartesian plots')
assert.doesNotMatch(tikz, /eval\(|new Function|dangerouslySetInnerHTML/, 'TikZ translation never evaluates model content')

assert.match(renderer, /tikzjax\.com\/v1\/tikzjax\.js/, 'browser renderer uses the TikZJax compiler')
assert.match(renderer, /sandbox="allow-scripts"/, 'TikZ compilation is isolated in a sandboxed iframe')
assert.match(renderer, /assessmentVisualTikzSource/, 'TikZ source is generated by GuroDesk, not supplied by Gemini')
assert.match(diagram, /AssessmentSvgDiagram/, 'deterministic SVG fallback remains available')

assert.match(clientGeneration, /dedupeAcceptedAnswers/, 'client generation normalizes redundant accepted answers')
assert.match(clientGeneration, /replace\(\/\[\.,;:\!\?\]\+\$\/u, ''\)/, 'accepted-answer dedupe ignores trailing punctuation-only variants')
assert.match(edgeContract, /uniqueAcceptedAnswers/, 'server contract normalizes redundant accepted answers')
assert.match(edgeContract, /replace\(\/\[\.,;:\!\?\]\+\$\/u, ''\)/, 'server dedupe ignores trailing punctuation-only variants')

assert.match(generator, /cartesianAxes/, 'Gemini prompt teaches the safe Cartesian primitive')
assert.match(generator, /cartesianPlot/, 'Gemini prompt teaches sampled Cartesian plots')
assert.match(generator, /never return TikZ/i, 'Gemini must never return executable TikZ')
assert.match(generator, /genuinely distinct/i, 'fill-in-the-blank prompt discourages duplicate accepted answers')

console.log('Assessment math visual validation passed: generated answers are deduplicated, math visuals remain a validated data DSL, Cartesian plots use sampled points, and GuroDesk deterministically compiles the safe model to TikZ with SVG fallback.')
