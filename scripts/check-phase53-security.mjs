import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')
const phase50 = read('supabase/migrations/202608080015_phase50_results_foundation.sql')
const phase53 = read('supabase/migrations/202608080016_phase53_remediation.sql')
const repository = read('src/lib/resultsRepository.ts')
const demo = read('src/lib/resultsDemo.ts')
const aiTypes = read('src/types/remediationAi.ts')
const aiClient = read('src/lib/remediationAi.ts')
const aiFunction = read('supabase/functions/remediation-suggester/index.ts')
const config = read('supabase/config.toml')

const failures = []
function assert(condition, message) {
  if (!condition) failures.push(message)
}

assert(/create table if not exists public\.class_learners/.test(phase50), 'class learner table missing')
assert(/create table if not exists public\.result_sessions/.test(phase50), 'result session table missing')
assert(/create table if not exists public\.result_item_outcomes/.test(phase50), 'normalized item outcome table missing')
assert(/create table if not exists public\.result_score_only_outcomes/.test(phase50), 'score-only outcome table missing')
assert(/section_name/.test(phase50) && /section_names/.test(phase50), 'assignment section ownership is not enforced')
assert(/auth\.uid\(\)/.test(phase50) && /security definer[\s\S]*set search_path = ''/.test(phase50), 'results security-definer ownership guards missing')
assert(/revoke all on public\.class_learners[\s\S]*from public/.test(phase50), 'roster direct writes are not revoked')
assert(/revoke all on public\.class_learners[\s\S]*result_item_outcomes[\s\S]*from public/.test(phase50), 'outcome direct writes are not revoked')
assert(/create or replace function public\.save_class_learners_bulk/.test(phase50), 'bulk roster RPC missing')
assert(/jsonb_array_length\(p_rows\)/.test(phase50) && /2 \* 1024 \* 1024/.test(phase50), 'bulk roster payload bound missing')
assert(/create or replace function public\.list_result_session_summaries\(\)/.test(phase50)
  && /encoded_learner_count/.test(phase50), 'owner-scoped result list summary RPC missing')
assert(/cardinality\(learner_ids\) < 1/.test(phase50), 'empty result learner sets are not rejected server-side')
assert(/ResultSessionListSummary/.test(repository) && /list_result_session_summaries/.test(repository), 'repository does not map bounded result list summaries')
assert(/delete from public\.result_item_outcomes where result_session_id = session_row\.id/.test(phase50), 'result save is not a complete outcome replacement')
assert(/delete from public\.result_score_only_outcomes where result_session_id = session_row\.id/.test(phase50), 'score-only save is not a complete replacement')
assert(/short_answer_mode\(coalesce\(p_short_answer_scoring, '\{\}'\), item_id\) = 'manual'/.test(phase50), 'manual omitted short-answer source is not teacher')
assert(/Only final result sessions may be archived/.test(phase50), 'draft result sessions may still be archived')
assert(/Teacher-scored short answers have no deterministic correctness flag/.test(phase50), 'manual short-answer correctness is not nullable')
assert(/multiple_choice' and answer is not null and not exists[\s\S]*immutable assessment choice/.test(phase50), 'MCQ choice IDs are not checked against the immutable answer key')
assert(/normalize\(coalesce\(p_value, ''\), NFKC\)/.test(phase50), 'server short-answer NFKC normalization missing')
assert(/octet_length\(answer::text\) > 4000/.test(phase50) && /octet_length\(p_short_answer_scoring::text\) > 8000/.test(phase50), 'answer/config byte bounds missing')
assert(/raw_score > possible_points/.test(phase50) && /Score-only points do not match/.test(phase50), 'score-only point bounds are not server validated')
assert(/create or replace function public\.result_answer_shape_valid/.test(phase50)
  && /jsonb_object_keys\(p_answer\)/.test(phase50)
  && /invalid minimized shape/.test(phase50), 'strict per-question answer shape allow-list missing')
assert(!/supabase\.from\(['"]result_item_outcomes['"]\)[\s\S]{0,300}\.insert/.test(repository), 'repository contains a per-outcome direct insert path')
assert(!/p_user_id|p_owner_id/.test(repository), 'repository sends a client-controlled owner ID')
assert(/loadResultRowsPaged/.test(repository) && /\.range\(offset, offset \+ pageSize - 1\)/.test(repository), 'result session loader lacks bounded pagination')
assert(/create table if not exists public\.remediation_plans/.test(phase53), 'remediation plan table missing')
assert(/foreign key \(result_session_id, user_id\)[\s\S]{0,120}references public\.result_sessions\(id, user_id\) on delete cascade/.test(phase53), 'draft result deletion does not cascade its dependent remediation plan')
assert(/create table if not exists public\.remediation_plan_targets/.test(phase53), 'remediation target snapshots missing')
assert(/create table if not exists public\.remediation_plan_participants/.test(phase53), 'remediation participant scope table missing')
assert(/alter table public\.remediation_plans enable row level security/.test(phase53)
  && /remediation_plans_select_own/.test(phase53), 'remediation RLS missing')
assert(/create or replace function public\.save_remediation_plan\(p_plan jsonb\)/.test(phase53)
  && /auth\.uid\(\)/.test(phase53), 'remediation RPC owner derivation missing')
assert(/remediation participant must belong to the plan result session/i.test(phase53), 'remediation participant/session guard missing')
assert(/teacher_reviewed/.test(phase53) && /review_state/.test(phase53), 'remediation teacher review state missing')
const remediationRepository = read('src/lib/remediationRepository.ts')
assert(/thresholdBasis/.test(remediationRepository) && /thresholdComparison/.test(remediationRepository)
  && /threshold: Number\(row\.threshold/.test(remediationRepository), 'remediation threshold settings do not round-trip through persistence')
assert(/verify_jwt = true/.test(config) && /\[functions\.remediation-suggester\][\s\S]*verify_jwt = true/.test(config), 'remediation function JWT verification missing')

const aiPromptStart = aiFunction.indexOf('function promptFor(')
const aiHandlerStart = aiFunction.indexOf('Deno.serve(')
const aiPromptEnd = aiFunction.indexOf('\nconst uuidPattern', aiPromptStart)
const aiPrompt = aiPromptStart >= 0 && aiPromptEnd > aiPromptStart
  ? aiFunction.slice(aiPromptStart, aiPromptEnd)
  : aiPromptStart >= 0 && aiHandlerStart > aiPromptStart ? aiFunction.slice(aiPromptStart, aiHandlerStart) : ''
assert(aiPrompt.length > 0, 'aggregate-only AI prompt builder missing')
assert(!/learner_id|participant_id|display_name|local_reference|learner_answer|teacher_feedback/i.test(aiPrompt), 'identity/raw response fields reach AI prompt builder')
assert(/select\('item_id, learner_answer, is_correct, earned_points, possible_points'\)/.test(aiFunction), 'AI function does not read answer presence for aggregate attempts')
assert(/loadOutcomeRows/.test(aiFunction) && /\.range\(offset, offset \+ pageSize - 1\)/.test(aiFunction), 'AI aggregate loader lacks bounded pagination')
assert(/const possible = attemptedOutcomes\.reduce/.test(aiFunction)
  && !/mappedPossiblePoints \* numberOfLearners/.test(aiFunction), 'AI point-facility denominator does not match attempted-response analysis')
assert(!/learner_answer|participant_id|learner_id|display_name|teacher_feedback/i.test(aiPrompt), 'forbidden learner/result fields reach AI prompt builder')
assert(/\.eq\('id', resultSessionId\)\.eq\('user_id', userId\)/.test(aiFunction), 'AI function does not recheck result-session ownership')
assert(/allowedConstraintKeys/.test(aiFunction) && /Unsupported remediation context field/.test(aiFunction), 'AI teacher-constraint allowlist missing')
assert(/resultSessionId: boundedText\(input\.resultSessionId/.test(aiClient)
  && /competencyId: boundedText\(input\.competencyId/.test(aiClient), 'client AI helper does not construct an allow-listed request')
assert(!/\.\.\.(session|analysis|input\.session|input\.analysis)/.test(aiClient), 'client AI helper spreads a session/analysis object')
assert(/NO learner|Do not include names, IDs, raw answers/i.test(aiFunction), 'AI privacy guardrail text missing')
assert(/createDemoResultsSample[\s\S]*answer,/.test(demo) && !/answer: null,\s*\n\s*isCorrect: objective/.test(demo), 'demo sample still stores null answers with scored outcomes')
assert(/scoreResultItem\(\{/.test(demo) && /normalizedOutcomes/.test(demo) && /shortAnswerMode: shortMode/.test(demo), 'demo persistence does not re-score outcomes with the authoritative scorer')
assert(/shortAnswerMode: 'manual'/.test(demo), 'demo sample does not use manual-mode authoritative scoring')
assert(/assessment\.assignmentId !== assignmentId/.test(demo), 'demo assessment/assignment integrity guard missing')
assert(/batch\.session\.assessmentSnapshot\.assignmentId/.test(demo), 'demo result snapshot integrity guard missing')
assert(/DEMO_REMEDIATION_KEY/.test(demo) && /plan\.resultSessionId === id/.test(demo), 'demo draft deletion does not clean up its dependent remediation plan')
assert(/RemediationAiRequest/.test(aiTypes), 'remediation AI request contract missing')

if (failures.length) {
  console.error(`Phase 5.3 security validation failed (${failures.length}):`)
  for (const failure of failures) console.error(`- ${failure}`)
  process.exit(1)
}
console.log('Phase 5.3 security validation passed: ownership/RLS, complete batch saves, roster batching, remediation scope, and aggregate-only AI boundary.')
