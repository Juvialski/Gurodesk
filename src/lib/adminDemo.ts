export function getDemoRegionStats(): AdminRegionStat[] {
  const map = new Map<string, { teachers: number; onboarded: number; docs: number; divisions: Set<string> }>()

  for (const t of DEMO_ADMIN_TEACHERS) {
    const current = map.get(t.region) ?? { teachers: 0, onboarded: 0, docs: 0, divisions: new Set<string>() }
    current.teachers += 1
    if (t.onboardingCompleted) current.onboarded += 1
    current.docs += t.totalDocumentsCount
    if (t.division) current.divisions.add(t.division)
    map.set(t.region, current)
  }

  return Array.from(map.entries()).map(([region, data]) => ({
    region,
    teacherCount: data.teachers,
    onboardingCount: data.onboarded,
    documentCount: data.docs,
    divisionsCount: data.divisions.size,
  })).sort((a, b) => b.teacherCount - a.teacherCount)
}

